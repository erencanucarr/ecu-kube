export function formatIssue(issue, lang) {
  const table = MESSAGES[lang] || MESSAGES.en;
  let tpl = table[issue.code] || MESSAGES.en[issue.code] || issue.code;
  const vars = Object.assign({}, issue.vars);
  if (typeof vars.path === "string") vars.path = shortPath(vars.path);
  for (const k of ["expected", "got"]) if (vars[k] && table["type." + vars[k]]) vars[k] = table["type." + vars[k]];
  tpl = tpl.replace(/\[\[([\s\S]*?)\]\]/g, (_, inner) => {
    const names = [...inner.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    return names.every((n) => vars[n] !== undefined && vars[n] !== "") ? inner : "";
  });
  let msg = tpl.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? "" : String(vars[k])));
  if (vars.more) msg += lang === "tr" ? ` (ardından ${vars.more} hata daha)` : ` (+${vars.more} more after this)`;
  return msg;
}

function shortPath(p) {
  const parts = p.split(".");
  return parts.length <= 2 ? p : parts.slice(-2).join(".");
}
